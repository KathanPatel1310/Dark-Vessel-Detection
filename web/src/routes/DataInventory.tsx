import { useEffect, useState } from 'react';
import { PageHeader, Card } from '../components/PageHeader';
import { ProvenanceChip } from '../components/ProvenanceChip';
import type { InventoryAsset, ProvenanceTag } from '../lib/api';
import { fetchInventory } from '../lib/api';

const ORDER: ProvenanceTag[] = ['REAL', 'DERIVED', 'SYNTHETIC', 'HEURISTIC', 'UNAVAILABLE'];
const BAR: Record<string, string> = { REAL: 'bg-emerald-500', DERIVED: 'bg-cyan-500', SYNTHETIC: 'bg-violet-500', HEURISTIC: 'bg-amber-500', UNAVAILABLE: 'bg-rose-500' };
const MEANING: Record<string, string> = {
  REAL: 'Observed data from an official or empirical source.',
  DERIVED: 'Computed from real data by deterministic code.',
  SYNTHETIC: 'Generated test data. Useful for exercising logic, never evidence.',
  HEURISTIC: 'A rule-based judgement, not a calibrated measurement.',
  UNAVAILABLE: 'Missing or withheld.',
};

const mb = (b?: number) => (b == null ? '—' : b > 1e6 ? `${(b / 1e6).toFixed(1)} MB` : `${(b / 1e3).toFixed(0)} KB`);

export const DataInventory = () => {
  const [assets, setAssets] = useState<InventoryAsset[] | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    fetchInventory().then((i) => setAssets(i.assets)).catch((e) => setError(e.message));
  }, []);

  const tally = (assets ?? []).reduce<Record<string, number>>((m, a) => ((m[a.provenance] = (m[a.provenance] ?? 0) + 1), m), {});
  const total = assets?.length ?? 0;

  return (
    <div>
      <PageHeader
        eyebrow="Reference"
        title="Data and provenance"
        lead="Where every input comes from, whether it is real, and what the platform can and cannot see."
      />
      <div className="mx-auto max-w-6xl space-y-8 px-4 py-8 sm:px-6">
        {error && <p className="text-sm text-rose-400">{error}. Is the API running?</p>}

        {assets && (
          <>
            <Card>
              <h2 className="font-display text-lg font-semibold text-white">Inputs by provenance</h2>
              <div className="mt-4 flex h-3 overflow-hidden rounded-full bg-white/5" role="img" aria-label="Share of data assets by provenance">
                {ORDER.filter((k) => tally[k]).map((k) => <div key={k} className={BAR[k]} style={{ width: `${(tally[k] / total) * 100}%` }} title={`${k}: ${tally[k]}`} />)}
              </div>
              <dl className="mt-5 grid gap-4 sm:grid-cols-2 lg:grid-cols-5">
                {ORDER.map((k) => (
                  <div key={k}>
                    <dt className="flex items-center gap-2"><ProvenanceChip provenance={k} /><span className="font-stat text-xl text-white">{tally[k] ?? 0}</span></dt>
                    <dd className="mt-1 text-xs leading-relaxed text-slate-400">{MEANING[k]}</dd>
                  </div>
                ))}
              </dl>
            </Card>

            <Card className="border-amber-500/30 bg-amber-950/10">
              <h2 className="font-display text-lg font-semibold text-white">Why do the benchmark scenarios say SYNTHETIC?</h2>
              <p className="mt-2 leading-relaxed text-slate-300">
                The five benchmark scenarios and the two large tables (35,000 detections, 103,120 AIS pings) were generated by code, even though the file names say “real”. They exist to exercise each decision path.
                Real evidence comes from the Sentinel-1 chips with the vessel’s own AIS — use <strong>Operations → Real Sentinel-1</strong>. Those chips are off the US Gulf coast, so the Arabian Sea EEZ/STS logic correctly reports “outside coverage” for them.
              </p>
            </Card>

            <div className="overflow-x-auto rounded-2xl border border-white/10">
              <table className="w-full min-w-[820px] text-left text-sm">
                <thead className="bg-[#0C1424] text-xs uppercase tracking-wide text-slate-400">
                  <tr><th className="p-3">Asset</th><th className="p-3">Provenance</th><th className="p-3">Count</th><th className="p-3">Size</th><th className="p-3">Source and notes</th></tr>
                </thead>
                <tbody className="divide-y divide-white/5">
                  {[...assets].sort((a, b) => ORDER.indexOf(a.provenance) - ORDER.indexOf(b.provenance)).map((a) => (
                    <tr key={a.id} className="align-top">
                      <td className="p-3"><div className="font-medium text-white">{a.name}</div><div className="mt-0.5 font-mono text-[11px] text-slate-500">{a.path}</div></td>
                      <td className="p-3"><ProvenanceChip provenance={a.provenance} /></td>
                      <td className="p-3 text-slate-200">{a.count != null ? `${a.count.toLocaleString()} ${a.unit ?? ''}` : '—'}</td>
                      <td className="p-3 text-slate-400">{mb(a.size_bytes)}</td>
                      <td className="max-w-md p-3 text-xs leading-relaxed text-slate-400">
                        {a.source} {a.details}
                        {a.sha256 && <div className="mt-1 break-all font-mono text-[10px] text-slate-600">SHA-256 {a.sha256}</div>}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </>
        )}
        {!assets && !error && <p className="text-slate-400">Loading…</p>}
      </div>
    </div>
  );
};
